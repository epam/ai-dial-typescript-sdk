import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.join(__dirname, '..');
const OPENAPI = path.join(REPO, 'open_api_core.yaml');
const API_PATHS_OUT = path.join(REPO, 'src', 'api-paths.ts');
const CLIENT_OUT = path.join(REPO, 'src', 'client.ts');

const HTTP = [
  'get',
  'put',
  'post',
  'delete',
  'options',
  'head',
  'patch',
  'trace',
];

function toClientMethod(verb) {
  return verb.toLowerCase() === 'delete' ? 'DELETE' : verb.toUpperCase();
}

/**
 * @param {string} p
 * @returns {string[]}
 */
function getPathParamNames(p) {
  return [...p.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
}

/**
 * @param {string} name
 */
function toPropertyKeyInType(name) {
  if (!/^[$_a-zA-Z][\w$]*$/.test(name) || /^\d/.test(name)) {
    return JSON.stringify(name);
  }
  return name;
}

/**
 * @param {string[]} paramNames
 */
function pathParamsTypeString(paramNames) {
  if (paramNames.length === 0) return null;
  const body = paramNames
    .map((n) => `${toPropertyKeyInType(n.toLowerCase())}: string`)
    .join(', ');
  return body;
}

function operationRequiresInit(op) {
  const hasRequiredRequestBody = op.requestBody?.required === true;
  const hasRequiredInitParam = (op.parameters ?? []).some(
    (param) =>
      param?.required === true &&
      param?.in &&
      param.in !== 'path' &&
      ['query', 'header', 'cookie'].includes(param.in),
  );

  return hasRequiredRequestBody || hasRequiredInitParam;
}

const doc = YAML.parse(fs.readFileSync(OPENAPI, 'utf8'));
const docPaths = doc.paths;
if (!docPaths) throw new Error('No paths in OpenAPI document');

const opMap = new Map();

for (const [p, item] of Object.entries(docPaths)) {
  for (const [verb, op] of Object.entries(item)) {
    if (!HTTP.includes(verb)) continue;
    if (!op || typeof op !== 'object' || !op.operationId) {
      continue;
    }
    const id = op.operationId;
    if (opMap.has(id)) {
      throw new Error(
        `Duplicate operationId: ${id}\n` +
          `  existing: ${opMap.get(id).path} ${opMap.get(id).httpVerb}\n` +
          `  new: ${p} ${verb}`,
      );
    }
    const pathParamNames = getPathParamNames(p);
    opMap.set(id, {
      path: p,
      method: toClientMethod(verb),
      httpVerb: verb,
      pathParamNames,
      requiresInit: operationRequiresInit(op),
    });
  }
}

const sortedIds = [...opMap.keys()].sort();

/** @param {string} p @returns {string} */
function escJsString(p) {
  return p.replaceAll('\\', '\\\\').replaceAll("'", "\\'");
}

const apiPathLines = [
  '/**',
  ' * Path templates (from `openapi.yaml`, one `export const` per `operationId`).',
  ' * Static paths are `as const` strings. Paths with `{param}` are functions: one `string` arg per',
  ' * segment (e.g. `(toolset_name: string) => ...`) or a single object when there are several `{...}` parts.',
  ' *',
  ' * @generated by `scripts/generate-sdk-client.mjs` — do not edit by hand; run `npm run gen`',
  ' */',
  '',
];

for (const id of sortedIds) {
  const p = opMap.get(id).path;
  const esc = escJsString(p);
  const names = getPathParamNames(p);

  if (names.length === 0) {
    apiPathLines.push(`export const ${id}Url = '${esc}';`);
    continue;
  }

  if (names.length === 1) {
    const n0 = names[0];
    if (/^[$_a-zA-Z][\w$]*$/.test(n0)) {
      const paramName = n0.toLowerCase();
      // Example: (toolset_name: string) => { void toolset_name; return '...' as const; }
      apiPathLines.push(
        `export const ${id}Url = (${paramName}: string) => { return \`${esc.replace(`{${n0}}`, `\${${paramName}}`)}\` };`,
      );
    }
  } else {
    const t = pathParamsTypeString(names);
    let url = esc;
    names.forEach((n) => {
      url = url.replace(`{${n}}`, `\${${n.toLowerCase()}}`);
    });
    apiPathLines.push(
      `export const ${id}Url = (${t}) => { return \`${url}\` };`,
    );
  }
  apiPathLines.push('');
}

const methodLines = sortedIds.map((id) => {
  const { method, pathParamNames } = opMap.get(id);

  if (id === 'getConversation') {
    return `    getConversation: (bucket: string, conversation_path: string, init?: any) =>\n      client.GET(\n        apiPaths.getConversationUrl(bucket, conversation_path) as any,\n        init,\n      ) as Promise<SDKResponse<Conversation>>,`;
  }

  if (id === 'saveConversation') {
    return `    saveConversation: (bucket: string, conversation_path: string, init?: any) =>\n      client.PUT(\n        apiPaths.saveConversationUrl(bucket, conversation_path) as any,\n        init,\n      ) as Promise<SDKResponse<ConversationResource>>,`;
  }

  if (pathParamNames.length === 0) {
    return `    ${id}: (init?: any) =>\n      client.${method}(apiPaths.${id}Url, init) as Promise<\n        SDKOperationResponse<operations[${JSON.stringify(id)}]>\n      >,`;
  }

  const t = pathParamsTypeString(pathParamNames);
  if (!t) {
    return `    ${id}: (init?: any) =>\n      client.${method}(apiPaths.${id}Url, init) as Promise<\n        SDKOperationResponse<operations[${JSON.stringify(id)}]>\n      >,`;
  }

  return `    ${id}: (${t}, init?: any) =>\n      client.${method}(apiPaths.${id}Url(${pathParamNames.map((p) => p.toLowerCase()).join(', ')}) as any, init) as Promise<\n        SDKOperationResponse<operations[${JSON.stringify(id)}]>\n      >,`;
});

const interfaceLines = sortedIds.map((id) => {
  const { pathParamNames, requiresInit } = opMap.get(id);
  const initParam = requiresInit
    ? `init: SDKOperationInit<operations[${JSON.stringify(id)}]>`
    : `init?: SDKOperationInit<operations[${JSON.stringify(id)}]>`;

  if (id === 'getConversation') {
    return `  getConversation: (\n    bucket: string,\n    conversation_path: string,\n    init?: SDKRequestInit,\n  ) => Promise<SDKResponse<Conversation>>;`;
  }

  if (id === 'saveConversation') {
    return `  saveConversation: (\n    bucket: string,\n    conversation_path: string,\n    init: SDKRequestInit<Conversation> & { body: Conversation },\n  ) => Promise<SDKResponse<ConversationResource>>;`;
  }

  if (pathParamNames.length === 0) {
    return `  ${id}: (${initParam}) => Promise<SDKOperationResponse<operations[${JSON.stringify(id)}]>>;`;
  }
  const t = pathParamsTypeString(pathParamNames);
  if (!t) {
    return `  ${id}: (${initParam}) => Promise<SDKOperationResponse<operations[${JSON.stringify(id)}]>>;`;
  }
  return `  ${id}: (${t}, ${initParam}) => Promise<SDKOperationResponse<operations[${JSON.stringify(id)}]>>;`;
});

const client = `/* eslint-disable no-unused-vars */
import createClient from 'openapi-fetch';

import * as apiPaths from './api-paths';
import type { operations, paths } from './schema';
import type {
  Conversation,
  ConversationResource,
  SDKOperationInit,
  SDKOperationResponse,
  SDKRequestInit,
  SDKResponse,
} from './types';

export interface SDKOptions {
  baseUrl: string;
  apiKey?: string;
  token?: string;
  headers?: Record<string, string>;
  fetch?: typeof fetch;
}

/** Methods exposed by \`createSDK\` (explicit shape avoids TS emit limits on the inferred return type). */
export interface DIAL_SDK {
${interfaceLines.join('\n')}
}

export function createSDK(opts: SDKOptions): DIAL_SDK {
  const client = createClient<paths>({
    baseUrl: opts.baseUrl,
    headers: {
      ...(opts.apiKey ? { 'Api-Key': opts.apiKey } : {}),
      ...(opts.token ? { Authorization: \`Bearer \${opts.token}\` } : {}),
      ...(opts.headers ?? {}),
    },
    fetch: opts.fetch,
  });

  return {
${methodLines.join('\n')}
  };
}
`;

fs.writeFileSync(API_PATHS_OUT, apiPathLines.join('\n') + '\n', 'utf8');
fs.writeFileSync(CLIENT_OUT, client, 'utf8');
